#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const DEFAULT_ROOT = path.resolve(__dirname, '..');
const DEFAULT_OUTPUT = path.join(DEFAULT_ROOT, 'src', 'router', 'viewRegistry.generated.ts');
const ROUTES_ROOT = path.join('src', 'router', 'routes');
const VIEW_IMPORT_RE = /import\(\s*['"]@\/views\/([^'"]+\.(?:vue|tsx))['"]\s*\)/g;
const FORBIDDEN_SEGMENTS = new Set([
  'demo',
  'mock',
  'test',
  'tests',
  'example',
  'examples',
  'template',
  'archive',
]);

class ViewRegistryError extends Error {}

function toPosix(value) {
  return value.split(path.sep).join('/');
}

function walkRouteSources(root) {
  const result = [];
  const pending = [root];
  while (pending.length) {
    const current = pending.pop();
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const target = path.join(current, entry.name);
      if (entry.isDirectory()) pending.push(target);
      if (entry.isFile() && entry.name.endsWith('.ts')) result.push(target);
    }
  }
  return result.sort((left, right) => toPosix(left).localeCompare(toPosix(right)));
}

function registryEntries(options = {}) {
  const root = path.resolve(options.root || DEFAULT_ROOT);
  const routesRoot = path.join(root, ROUTES_ROOT);
  if (!fs.existsSync(routesRoot)) {
    throw new ViewRegistryError(`missing formal route source root: ${ROUTES_ROOT}`);
  }

  const entries = new Map();
  for (const sourcePath of walkRouteSources(routesRoot)) {
    const source = fs.readFileSync(sourcePath, 'utf8');
    for (const match of source.matchAll(VIEW_IMPORT_RE)) {
      const relative = match[1];
      const key = relative.replace(/\.(?:vue|tsx)$/i, '');
      const segments = key.toLowerCase().split('/');
      if (segments.some((segment) => FORBIDDEN_SEGMENTS.has(segment))) {
        throw new ViewRegistryError(`forbidden View key referenced by formal route: ${key}`);
      }
      const target = path.join(root, 'src', 'views', relative);
      if (!fs.existsSync(target)) {
        throw new ViewRegistryError(
          `formal route references missing View: ${toPosix(path.relative(root, sourcePath))} -> ${relative}`,
        );
      }
      const previous = entries.get(key);
      if (previous && previous !== relative) {
        throw new ViewRegistryError(`duplicate View key ${key}: ${previous} and ${relative}`);
      }
      entries.set(key, relative);
    }
  }

  if (!entries.size) throw new ViewRegistryError('formal route sources contain no View imports');
  return [...entries.entries()]
    .map(([key, relative]) => ({ key, relative }))
    .sort((left, right) => left.key.localeCompare(right.key));
}

function renderRegistry(entries) {
  const lines = [
    '/* This file is generated by scripts/formal-view-registry.cjs. */',
    'export type ViewLoader = () => Promise<unknown>;',
    '',
    'export const viewRegistry = {',
  ];
  for (const entry of entries) {
    lines.push(`  '${entry.key}': () => import('@/views/${entry.relative}'),`);
  }
  lines.push(
    '} as const satisfies Readonly<Record<string, ViewLoader>>;',
    '',
    'export type ViewRegistryKey = keyof typeof viewRegistry;',
    '',
    'export function normalizeViewKey(value: string): string | null {',
    "  const normalized = value.trim().replace(/\\\\/g, '/').replace(/^@\\/views\\//, '');",
    "  const withoutPrefix = normalized.replace(/^\\.\\.\\/\\.\\.\\/views\\//, '').replace(/^\\//, '');",
    "  const withoutExtension = withoutPrefix.replace(/\\.(?:vue|tsx)$/i, '');",
    "  if (!withoutExtension || withoutExtension.includes('..') || /[?#\\0]/.test(withoutExtension)) {",
    '    return null;',
    '  }',
    "  if (!/^[A-Za-z0-9_@.-]+(?:\\/[A-Za-z0-9_@.-]+)*$/.test(withoutExtension)) {",
    '    return null;',
    '  }',
    '  return withoutExtension;',
    '}',
    '',
    'export function resolveViewComponent(value: string): ViewLoader | undefined {',
    '  const key = normalizeViewKey(value);',
    '  return key ? viewRegistry[key as ViewRegistryKey] : undefined;',
    '}',
    '',
  );
  return `${lines.join('\n')}\n`;
}

function generatedBytes(options = {}) {
  return Buffer.from(renderRegistry(registryEntries(options)), 'utf8');
}

function writeRegistry(options = {}) {
  const output = path.resolve(options.output || DEFAULT_OUTPUT);
  const bytes = generatedBytes(options);
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, bytes);
  return { output, bytes, entries: registryEntries(options) };
}

function checkRegistry(options = {}) {
  const output = path.resolve(options.output || DEFAULT_OUTPUT);
  if (!fs.existsSync(output)) {
    throw new ViewRegistryError(
      `View Registry is missing: ${output}; run node scripts/formal-view-registry.cjs --write`,
    );
  }
  const expected = generatedBytes(options);
  const actual = fs.readFileSync(output);
  if (!actual.equals(expected)) {
    throw new ViewRegistryError(
      `View Registry drift detected: ${output}; run node scripts/formal-view-registry.cjs --write`,
    );
  }
  return { output, bytes: actual, entries: registryEntries(options) };
}

function main(argv = process.argv.slice(2)) {
  const write = argv.includes('--write');
  const check = argv.includes('--check');
  if (write === check) throw new ViewRegistryError('choose exactly one command: --write or --check');
  const result = write ? writeRegistry() : checkRegistry();
  console.log(
    `Formal View Registry ${write ? 'wrote' : 'verified'}: ${path.relative(DEFAULT_ROOT, result.output)} (${result.entries.length} entries)`,
  );
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}

module.exports = {
  DEFAULT_OUTPUT,
  ViewRegistryError,
  checkRegistry,
  generatedBytes,
  registryEntries,
  renderRegistry,
  writeRegistry,
};
